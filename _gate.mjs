import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport:{width:390,height:760} })).newPage();
await p.goto('https://jacelovesbass.github.io/huddle/');
await p.waitForSelector('.gate');
await p.getByPlaceholder('Your name').fill('Jason');
await p.getByRole('button',{name:'Continue'}).click();
await p.waitForTimeout(800);
await p.screenshot({ path:'gate.png' });
await b.close();
